import { indent, joinBlocks } from "./lines.ts";
import { lowerDefinition } from "./lower.ts";
import { camelCase, pascalCase, swiftString } from "./naming.ts";
import { renderDecl } from "./render.ts";
import { refName, resolve, type ProtocolDocument } from "./schema.ts";

// Unions that must keep decoding when a newer engine adds a variant (PLAN.md §4.4: events are a versioned union).
const openUnions = new Set(["SessionEvent"]);
const eventUnion = "SessionEvent";

const header = ["// Generated by `make codegen` from engine/packages/protocol/protocol.schema.json. Do not edit.", ""];

function sortedNames(names: Iterable<string>): string[] {
  return [...names].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function render(blocks: readonly (readonly string[])[]): string {
  return `${[...header, ...joinBlocks(blocks)].join("\n")}\n`;
}

function eventDefinitionNames(document: ProtocolDocument): Set<string> {
  const names = new Set([eventUnion]);
  for (const ref of Object.values(document["x-pica-events"])) {
    const name = refName(ref.$ref);
    names.add(name);
    const payload = resolve(document, ref).properties?.payload?.$ref;
    if (payload !== undefined && refName(payload).endsWith("Payload")) {
      names.add(refName(payload));
    }
  }
  return names;
}

function renderDefinitions(document: ProtocolDocument, names: readonly string[]): string {
  return render(
    names.map((name) => {
      const node = document.$defs[name];
      if (node === undefined) {
        throw new Error(`no definition named ${name}`);
      }
      return renderDecl(lowerDefinition(document, name, node, openUnions));
    }),
  );
}

function directionCase(direction: string): string {
  const name = camelCase(direction);
  return name === direction ? `case ${name}` : `case ${name} = ${swiftString(direction)}`;
}

function renderMethods(document: ProtocolDocument): string {
  const methods = Object.entries(document["x-pica-methods"]);
  const directions = sortedNames(new Set(methods.map(([, method]) => method.direction)));
  const methodBlocks = methods.map(([name, method]) => [
    `public enum ${pascalCase(name)}: PicaMethod {`,
    ...indent([
      `public typealias Params = ${refName(method.params.$ref)}`,
      `public typealias Result = ${refName(method.result.$ref)}`,
      `public static let name = ${swiftString(name)}`,
      `public static let direction = MethodDirection.${camelCase(method.direction)}`,
    ]),
    "}",
  ]);
  const notificationBlocks = Object.entries(document["x-pica-notifications"]).map(([name, notification]) => [
    `public enum ${pascalCase(name)}: PicaNotification {`,
    ...indent([`public typealias Params = ${refName(notification.params.$ref)}`, `public static let name = ${swiftString(name)}`]),
    "}",
  ]);
  return render([
    ["public enum MethodDirection: String, CaseIterable, Sendable {", ...indent(directions.map(directionCase)), "}"],
    ["public enum Methods {", ...indent(joinBlocks(methodBlocks)), "}"],
    ["public enum Notifications {", ...indent(joinBlocks(notificationBlocks)), "}"],
  ]);
}

function renderConstants(document: ProtocolDocument): string {
  const version = document["x-pica-protocol-version"];
  const errorNumbers = Object.entries(document["x-pica-rpc-error-numbers"]).map(([name, value]) => `case ${camelCase(name)} = ${String(value)}`);
  return render([
    ["extension ProtocolVersion {", ...indent([`public static let current = ProtocolVersion(major: ${String(version.major)}, minor: ${String(version.minor)})`]), "}"],
    ["public enum RpcErrorNumber: Int, CaseIterable, Sendable {", ...indent(errorNumbers), "}"],
  ]);
}

// File name → contents, all under the PicaProtocol target's Generated directory.
export function generateSwift(document: ProtocolDocument): Record<string, string> {
  const eventNames = eventDefinitionNames(document);
  const allNames = sortedNames(Object.keys(document.$defs));
  return {
    "Constants.swift": renderConstants(document),
    "Definitions.swift": renderDefinitions(document, allNames.filter((name) => !eventNames.has(name))),
    "Events.swift": renderDefinitions(document, [eventUnion, ...allNames.filter((name) => eventNames.has(name) && name !== eventUnion)]),
    "Methods.swift": renderMethods(document),
  };
}
